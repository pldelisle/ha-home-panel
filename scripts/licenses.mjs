// Writes LICENSES.md: a table of the production dependencies with version, licence and repository, then each licence
// text. `npm run licenses` regenerates it; test/unit/licenses.test.mjs fails when it is out of date.
//
// What it lists is the whole production tree: every package npm installs for `dependencies` (ApexCharts and Mermaid
// with what they pull in), as license-checker-rseidelsohn's --production reads it from node_modules. Vite tree-shakes
// part of that tree out of the chunks, and some packages hold only type declarations, but telling which is the build's
// job and would change with every Mermaid release; listing a package that does not ship costs a line, and leaving out
// one that does would be a licence breach, so the list errs on the long side.
//
// The output depends on the installed tree and on nothing else: rows sorted by code point (no locale), line ends
// and trailing spaces normalised, no path, date or machine name in it. The same lock file gives the same file on a Mac
// and on Linux.
import {readFileSync, realpathSync, writeFileSync} from 'node:fs';
import {basename} from 'node:path';
import {fileURLToPath} from 'node:url';
import {init} from 'license-checker-rseidelsohn';

const ROOT = fileURLToPath(new URL('../', import.meta.url));

// license-checker's licence file can be a README (it falls back to one when a package has no licence file); a README
// is not the licence text
const isLicenseFile = file => /^(licen[cs]e|copying)/i.test(basename(file));

// the same text on every machine: LF line ends, no trailing spaces, no blank lines around it
const clean = text =>
  text
    .replaceAll('\r\n', '\n')
    .replaceAll(/[ \t]+$/gm, '')
    .trim();

const cell = text => String(text ?? '').replaceAll('|', '\\|');

// a fence longer than any run of backticks in the text, so a licence that contains ``` cannot end its own block
const fence = text => '`'.repeat(Math.max(3, ...[...text.matchAll(/`+/g)].map(m => m[0].length + 1)));

const byCodePoint = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const scan = () =>
  new Promise((resolve, reject) =>
    init({start: ROOT, production: true, excludePrivatePackages: true}, (error, found) =>
      error ? reject(error) : resolve(found),
    ),
  );

/** The text of LICENSES.md for the packages installed under the repository root. */
export async function renderLicenses() {
  const found = await scan();
  const rows = Object.entries(found)
    .map(([key, info]) => {
      const at = key.lastIndexOf('@'); // the last one: a scoped name starts with one
      const licenses = [info.licenses].flat().join(', ');
      const text =
        info.licenseFile && isLicenseFile(info.licenseFile) ? clean(readFileSync(info.licenseFile, 'utf8')) : '';
      return {
        name: key.slice(0, at),
        version: key.slice(at + 1),
        licenses,
        repository: info.repository ?? '',
        text: text || `This package ships no licence file; its package.json declares ${licenses}.`,
      };
    })
    .sort((a, b) => byCodePoint(a.name, b.name) || byCodePoint(a.version, b.version));
  const unknown = rows.filter(r => /UNKNOWN|UNLICENSED/.test(r.licenses));
  if (unknown.length)
    throw new Error(
      `No licence found for ${unknown.map(r => `${r.name}@${r.version}`).join(', ')}; read it and decide.`,
    );

  let md =
    '# Licences\n\n' +
    'Generated by `npm run licenses`; edit nothing here by hand. The libraries that ship with the panel, their versions and licences.\n\n' +
    'The list is the whole production dependency tree of ApexCharts and Mermaid as npm installs it. The build leaves some of those packages out of the chunks ' +
    '(tree shaking; some hold only type declarations), and the list does not say which: a package that might ship is listed. ' +
    'An asterisk after a licence means it was read from the licence file, not declared by the package. The panel itself is MIT, see [LICENSE](LICENSE).\n\n' +
    '| Package | Version | Licence | Source |\n|---|---|---|---|\n';
  for (const r of rows)
    md += `| ${cell(r.name)} | ${cell(r.version)} | ${cell(r.licenses)} | ${cell(r.repository)} |\n`;
  for (const r of rows) {
    const f = fence(r.text);
    md += `\n## ${r.name} ${r.version}\n\n${f}\n${r.text}\n${f}\n`;
  }
  return md;
}

// run directly (also through a symlink), not when a test imports it
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  // an optional path to write to instead of LICENSES.md (to compare runs on two machines)
  const out = process.argv[2] ?? `${ROOT}LICENSES.md`;
  const md = await renderLicenses();
  writeFileSync(out, md);
  console.log(`${out}: ${md.split('\n').filter(l => l.startsWith('| ')).length - 1} packages`);
}
